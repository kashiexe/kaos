; =========== COMMON ISR ===========
;
; Helps generate common ISR handlers and wrappers for the ISRs
;
; ==================================
[BITS 32]
[EXTERN isr_handler]
[GLOBAL isr_common]

; ISR without error code
%macro ISR_NOERR 1
global isr%1
isr%1:
    push dword 0
    push dword %1
    jmp isr_common
%endmacro

; ISR with error code
%macro ISR_ERR 1
global isr%1
isr%1:
    push dword %1
    jmp isr_common
%endmacro

; common stub for all ISRs
isr_common:
    pusha

    ; save data segments
    push ds
    push es
    push fs
    push gs

    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax

    ; push esp
    cld
    push esp
    call isr_handler
    add esp, 4

    ; restore data segments
    pop gs
    pop fs
    pop es
    pop ds

    ; restore segment regs
    popa

    add esp, 8 ; remove error code and interrupt number from stack
    iret

